/**
 * 다음 달 1일을 구한다. 월 연속성을 검사하는 데 쓴다.
 * @param month YYYY-MM-DD 형식의 월 1일.
 * @returns 다음 달 1일 문자열, 형식이 아니면 null.
 */
function nextMonth(month: string): string | null {
  const m = /^(\d{4})-(\d{2})-(\d{2})$/.exec(month);
  if (!m) return null;
  if (m[3] !== "01") return null;
  let year = Number(m[1]);
  let mon = Number(m[2]);
  if (!Number.isSafeInteger(year) || !Number.isSafeInteger(mon) || mon < 1 || mon > 12) return null;
  mon += 1;
  if (mon > 12) {
    mon = 1;
    year += 1;
  }
  return `${String(year).padStart(4, "0")}-${String(mon).padStart(2, "0")}-01`;
}

/**
 * 고정 KUSH 월간 운영-관심 시계열을 검사한다. 0을 결측으로 바꾸지 않는다.
 * @param value 091-KUSH-Z 런 JSON.
 * @returns 검증된 관심 시계열 또는 오류 상태.
 */
export function readKushMonthly(value: unknown): KushMonthlySeries | null {
  const v = value as { runId?: unknown; source?: unknown; label?: unknown; rows?: KushMonthlyRow[] };
  if (!v || v.runId !== RUN_ID || v.source !== SOURCE || v.label !== LABEL) return null;
  if (!Array.isArray(v.rows) || v.rows.length !== EXPECTED.length) return null;
  let sum = 0;
  for (let i = 0; i < EXPECTED.length; i++) {
    const row = v.rows[i] as KushMonthlyRow;
    const [month, count] = EXPECTED[i];
    if (!row || row.month !== month) return null;
    if (typeof row.articleCount !== "number" || !Number.isSafeInteger(row.articleCount)) return null;
    if (row.articleCount < 0 || row.articleCount > 3) return null;
    if (row.articleCount !== count) return null;
    if (i > 0 && nextMonth((v.rows[i - 1] as KushMonthlyRow).month) !== row.month) return null;
    sum += row.articleCount;
  }
  if (v.rows[0].month !== FIRST_MONTH || v.rows[v.rows.length - 1].month !== LAST_MONTH) return null;
  if (sum !== ARTICLE_SUM) return null;
  return v as KushMonthlySeries;
}

/**
 * 시계열에서 한 달의 관심 기사 수를 꺼낸다. 0도 정상 관측이다.
 * @param series 검증된 KUSH 월간 시계열.
 * @param month YYYY-MM-DD 형식의 월 1일 (예: 2026-06-01).
 * @returns 해당 월 행 또는 없으면 null.
 */
export function monthAttention(
  series: KushMonthlySeries | null,
  month: string,
): KushMonthlyRow | null {
  if (!series || series.runId !== RUN_ID) return null;
  const row = series.rows.find((r) => r.month === month);
  return row ?? null;
}
