/**
 * 고정 NBI Payne County 교량 점검 로그를 검사한다. 주 전체를 Payne으로 바꾸지 않는다.
 * @param value 091-NBI-Z 런 JSON.
 * @returns 검증된 교량 목록 또는 오류 상태.
 */
export function readCushingNbi(value: unknown): CushingNbiSeries | null {
  const v = value as {
    runId?: unknown; geography?: unknown; source?: unknown; sourceUrl?: unknown;
    inventoryYear?: unknown; rows?: CushingNbiBridge[];
  };
  if (!v || v.runId !== RUN_ID || v.geography !== GEOGRAPHY) return null;
  if (v.source !== SOURCE || v.sourceUrl !== SOURCE_URL) return null;
  if (v.inventoryYear !== INVENTORY_YEAR) return null;
  if (!Array.isArray(v.rows) || v.rows.length !== EXPECTED.length) return null;
  for (let i = 0; i < EXPECTED.length; i++) {
    const row = v.rows[i] as CushingNbiBridge;
    const [structureNumber, inspectionYm, deck, superstructure, substructure, culvert] = EXPECTED[i];
    if (!row || row.structureNumber !== structureNumber) return null;
    if (row.countyCode !== COUNTY || row.inspectionYm !== inspectionYm) return null;
    if (row.inspectionRaw !== inspectionYm.slice(5, 7) + inspectionYm.slice(2, 4)) return null;
    if (row.deck !== deck || row.superstructure !== superstructure) return null;
    if (row.substructure !== substructure || row.culvert !== culvert) return null;
    if (!/^\d{4}-\d{2}$/.test(row.inspectionYm)) return null;
    if (!/^\d{4}$/.test(row.inspectionRaw)) return null;
    if (!/^\d{5}$/.test(row.placeCode)) return null;
    if (!/^\d{8}$/.test(row.latitude) || !/^\d{9}$/.test(row.longitude)) return null;
    if (!/^\d{4}$/.test(row.yearBuilt) || !/^\d{4}$/.test(row.yearReconstructed)) return null;
    if (!/^\d{2}$/.test(row.inspectionFrequencyMonths)) return null;
    if (!Number.isInteger(row.adt) || row.adt < 0) return null;
    if (!/^\d{4}$/.test(row.adtYear)) return null;
    if (i > 0) {
      const prev = v.rows[i - 1] as CushingNbiBridge;
      if (prev.inspectionYm > row.inspectionYm) return null;
      if (prev.inspectionYm === row.inspectionYm && prev.structureNumber >= row.structureNumber) return null;
    }
  }
  return v as CushingNbiSeries;
}

/**
 * 지정 점검월의 Payne County 교량을 꺼낸다. 한 달에 여러 건이 있다.
 * @param series 검증된 NBI Payne County 교량 목록.
 * @param inspectionYm 점검월 (예: 2023-09).
 * @returns 해당 점검월 행 목록 또는 없으면 빈 배열.
 */
export function nbiBridgesOn(series: CushingNbiSeries | null, inspectionYm: string): CushingNbiBridge[] {
  if (!series || series.runId !== RUN_ID) return [];
  return series.rows.filter((r) => r.inspectionYm === inspectionYm);
}

/**
 * 지정 연도에 점검된 Payne County 교량 수를 센다. 결측 연도는 세지 않고 0을 채우지 않는다.
 * @param series 검증된 NBI Payne County 교량 목록.
 * @param year 연도 (예: 2023).
 * @returns 해당 연도 점검 교량 수.
 */
export function nbiBridgesInspectedInYear(series: CushingNbiSeries | null, year: number): number {
  if (!series || series.runId !== RUN_ID) return 0;
  const prefix = String(year) + "-";
  let count = 0;
  for (const r of series.rows) {
    if (r.inspectionYm.startsWith(prefix)) count++;
  }
  return count;
}
